#!/usr/bin/env python3
"""The panel of MONK (MONK-1's formant choir) in the instruments' look (tools/panels/gpanel.py).

Usage:  monk_panel.py real           -> instruments/res/Monk.svg (text as paths) + instruments/src/monk/MonkLayout.hpp
        monk_panel.py preview OUT.png
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gpanel  # noqa: E402

K = ["VOWEL", "HEAD", "BREATH", "GLIDE", "VOICES", "DETUNE", "SPREAD", "TUNE"]  # K0..K7; VOWEL (K0) is the large one
SPEC = dict(
    name="MONK", sub="GENRA · FORMANT VOICE", subshort="FORMANT VOICE", acc="#ffb43d", preset="01  JERRY", dh=22, screen=22,
    rows=[
        [dict(title="SING · CHOIR", cols=[[("large", "K0", "VOWEL")], [("knob", "K1", "HEAD"), ("small", "K4", "VOICES")],
                                         [("knob", "K2", "BREATH"), ("small", "K5", "DETUNE")],
                                         [("knob", "K3", "GLIDE"), ("small", "K6", "SPREAD")], [("knob", "K7", "TUNE")]]),
         dict(title="PRESS", cols=[[("knob", "PDEPTH", "DEPTH")], [("knob", "VELSENS", "VEL")], [("knob", "LEVEL", "LEVEL")]],
              lamps=[("ROUTE", "", ["VOWEL", "PITCH", "BOTH", "INV"])])],
        [dict(title="ENVELOPE", cols=[[("small", "ATK", "A")], [("small", "DEC", "D")], [("small", "SUS", "S")], [("small", "REL", "R")]]),
         dict(title="VIBRATO · ECHO", cols=[[("small", "VIBD", "DEPTH")], [("small", "VIBR", "RATE")], [("small", "ECHO", "ECHO")],
                                           [("small", "TIME", "TIME")], [("small", "FB", "FDBK")]])],
    ],
    strip=[("VOCT", "V/OCT"), ("GATE", "GATE"), ("VEL", "VEL")], sync=[("PRESS", "PRESS"), ("SINGER", "SINGER")],
    cvs=[[(f"K_IN{k}", K[k]) for k in range(8)]],
    outs=[("OUT_ENV", "ENV"), ("OUT_DRY", "DRY"), ("OUT_L", "L"), ("OUT_R", "R")])

p = gpanel.build(SPEC)
if not gpanel.preview(p, "Monk"):
    open(os.path.join(gpanel.ROOT, "instruments", "res", "Monk.svg"), "w").write(gpanel.svg(p))
    hdr = ["// Generated by tools/panels/monk_panel.py - do not edit", "// Rack pixels (1 HP = 15 px).", "#pragma once",
           gpanel.layout(p, None, "monk"), ""]
    open(os.path.join(gpanel.ROOT, "instruments", "src", "monk", "MonkLayout.hpp"), "w").write("\n".join(hdr))
    print(f"Monk: {p.hp} HP, written instruments/res/Monk.svg instruments/src/monk/MonkLayout.hpp")
