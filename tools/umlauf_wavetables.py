#!/usr/bin/env python3
"""UMLAUF's own band-limited tables for the voices LXR TONE, LXR METAL and BAZZ (instruments/vader/src/zynth/lxrtab/).

VADER reads the LXR02 firmware's tables for these three voices. Their licence (LXR02 Open-Source) forbids commercial
use, which GPL-3.0 (this plugin's licence) does not allow to add, so UMLAUF computes tables of the same shape instead and
leaves the LXR02 code out:
  sine_table  4097 samples of -cos (from -1 at 0)
  sawTable, recTable, triTable  11 tables of 1024 samples, one per octave (MIDI notes 0, 12, ... 120 at 44.1 kHz):
  saw: sum sin(n x)/n, square: odd sin(n x)/n, triangle: odd -cos(n x)/n^2, each with every harmonic of the octave's top
  note below 22 kHz, softened by Lanczos sigma (no ringing), scaled to a peak of 32767.

    umlauf_wavetables.py OUT_DIR"""
import math
import os
import sys

OUT = sys.argv[1]
N = 1024


def table(kind, k):
    f0 = 8.1758 * 2 ** k
    h_max = max(1, min(N // 2 - 1, int(22000 / (2 * f0))))
    y = [0.0] * N
    for n in range(1, h_max + 1):
        if kind != "saw" and n % 2 == 0:
            continue
        sigma = 1.0 if h_max == 1 else math.sin(math.pi * n / (h_max + 1)) / (math.pi * n / (h_max + 1))
        for i in range(N):
            x = 2 * math.pi * i / N
            y[i] += sigma * (-math.cos(n * x) / (n * n) if kind == "tri" else math.sin(n * x) / n)
    peak = max(abs(v) for v in y) or 1.0
    return [int(round(32767 * v / peak)) for v in y]


def rows(vals, per=16):
    return ",\n".join("    " + ", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))


os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "wavetable.h"), "w") as f:
    f.write("""/* UMLAUF: band-limited tables in place of the LXR02 firmware's (tools/umlauf_wavetables.py, generated). */
#ifndef WAVETABLES_H_
#define WAVETABLES_H_
#include <stdint.h>
#define TABLESIZE 4096
#define TABLES 128
extern const int16_t sine_table[TABLESIZE + 1];
/* one table per octave: MIDI notes 0, 12, 24, ... 120 */
extern const int16_t recTable[11][1024];
extern const int16_t triTable[11][1024];
extern const int16_t sawTable[11][1024];
#endif
""")
with open(os.path.join(OUT, "wavetable.c"), "w") as f:
    f.write("/* UMLAUF: generated by tools/umlauf_wavetables.py - do not edit. GPL-3.0-only (GENRA SYNTHIS). */\n")
    f.write('#include "wavetable.h"\n\n')
    sine = [int(round(-32767 * math.cos(2 * math.pi * i / 4096))) for i in range(4097)]
    f.write("const int16_t sine_table[TABLESIZE + 1] = {\n" + rows(sine) + "};\n\n")
    for name, kind in (("sawTable", "saw"), ("recTable", "rec"), ("triTable", "tri")):
        f.write(f"const int16_t {name}[11][1024] = {{\n")
        f.write(",\n".join("  {\n" + rows(table(kind, k)) + "}" for k in range(11)))
        f.write("};\n\n")
print("wrote", OUT)
