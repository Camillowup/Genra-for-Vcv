/* SPDX-License-Identifier: GPL-3.0-only
 * The GOLANA core without Rack: every preset plays a phrase (notes, a held chord; an arp preset its chord), must sound,
 * stay finite and end; LFO retrigger, sync, the virtual values and the parameters' clamping. With an argument it prints
 * src/golana/GolanaLevels.hpp (the gain that makes each preset as loud as the others).
 *   gcc -std=gnu11 -O2 -w -Iglcore -Igolana/gen test/glcore_test.c -o gt -lm && ./gt [levels] */
#include "../glcore/glcore.c"
#include <assert.h>

static const gl_api *A;
static double sum2;
static float peak;
static uint64_t nfr;
static int bad;

static void run(uint32_t frames)
{
    uint32_t k;
    while (frames) {
        const float *f = A->render();
        for (k = 0; k < GL_FRAMES; k++) {
            float l = f[2 * k], r = f[2 * k + 1];
            if (!(l == l) || !(r == r) || l > 4.f || l < -4.f) {
                bad = 1;
            }
            sum2 += (double)l * l + (double)r * r;
            if (fabsf(l) > peak) peak = fabsf(l);
            if (fabsf(r) > peak) peak = fabsf(r);
            nfr++;
        }
        frames = frames > GL_FRAMES ? frames - GL_FRAMES : 0;
    }
}
static float tail_level(uint32_t frames)
{
    float m = 0.f;
    uint32_t k;
    while (frames) {
        const float *f = A->render();
        for (k = 0; k < 2 * GL_FRAMES; k++)
            if (fabsf(f[k]) > m) m = fabsf(f[k]);
        frames = frames > GL_FRAMES ? frames - GL_FRAMES : 0;
    }
    return m;
}

int main(int argc, char **argv)
{
    static const uint8_t MEL[8] = {48, 55, 60, 63, 67, 70, 72, 60};
    uint32_t n, i, k;
    int levels = argc > 1;
    A = gl_get();
    assert(A->api == GL_API_VERSION && A->sample_rate() == 44100u);
    A->init();
    n = A->npresets();
    assert(n == 55u);
    if (levels)
        printf("// SPDX-License-Identifier: GPL-3.0-only\n// Generated by test/glcore_test.c levels: the output gain "
               "that makes each preset as loud as the others (a phrase and a chord at 120 BPM, RMS to -12 dBFS).\n"
               "#pragma once\nnamespace gllevels {\nstatic const float PRESET_GAIN[] = {\n");
    for (i = 0; i < n; i++) {
        double rms;
        float tail, gain;
        int arp;
        A->init();
        A->load_preset(i);
        arp = A->get(GL_ARPON) != 0;
        sum2 = 0;
        peak = 0;
        nfr = 0;
        bad = 0;
        if (!arp)
            for (k = 0; k < 8u; k++) {
                A->midi(0x90, MEL[k], 100);
                run(9700);
                A->midi(0x80, MEL[k], 0);
                run(1300);
            }
        A->midi(0x90, 48, 100);
        A->midi(0x90, 55, 100);
        A->midi(0x90, 63, 100);
        A->midi(0x90, 67, 100);
        run(arp ? 44100 * 4 : 44100 * 2);
        A->midi(0x80, 48, 0);
        A->midi(0x80, 55, 0);
        A->midi(0x80, 63, 0);
        A->midi(0x80, 67, 0);
        rms = sqrt(sum2 / (2.0 * (double)nfr));
        run(44100 * 12);
        tail = tail_level(44100);
        gain = rms > 1e-6 ? (float)(0.25 / rms) : 1.f;
        if (gain > 4.f) gain = 4.f;
        if (levels)
            printf("\t%.3ff,  // %u %s · %s\n", gain, i, A->preset_style(i), A->preset_name(i));
        else
            printf("%2u %-24s %-26s rms %6.1f dB  peak %6.1f dB  tail %.5f%s\n", i, A->preset_style(i),
                   A->preset_name(i), 20.0 * log10(rms + 1e-12), 20.0 * log10(peak + 1e-12), tail,
                   bad ? "  BAD" : "");
        if (bad || rms < 1e-4 || tail > 0.01f) {
            fprintf(stderr, "preset %u %s: %s\n", i, A->preset_name(i),
                    bad ? "not finite / too loud" : rms < 1e-4 ? "silent" : "does not end");
            return 1;
        }
    }
    if (levels) {
        printf("};\ninline float gainOf(int i) {\n\treturn i >= 0 && i < (int) (sizeof(PRESET_GAIN) / sizeof(PRESET_GAIN[0])) "
               "? PRESET_GAIN[i] : 1.f;\n}\n}  // namespace gllevels\n");
        return 0;
    }
    /* the parameters clamp to the firmware's range; the virtual values */
    A->init();
    A->set(GL_CUTOFF, 500);
    assert(A->get(GL_CUTOFF) == A->hi(GL_CUTOFF));
    A->set(GL_FEGINT, -500);
    assert(A->get(GL_FEGINT) == -63);
    A->vset(GLV_ARPRES, 4);
    assert(A->vget(GLV_ARPRES) == 4);
    A->vset(GLV_BPM, 999);
    assert(A->vget(GLV_BPM) == 240);
    A->vset(GLV_DMIX, 50);
    run(GL_FRAMES);
    assert(A->vget(GLV_DMIX) == 50 && song.g[G_DMIX] == 50);
    {
        char t[32];
        A->text(GL_FTYPE, t, sizeof t);
        assert(strcmp(t, "LPF24") == 0);
    }
    /* retrigger and sync do not break the sound */
    A->load_preset(19);
    A->midi(0x90, 40, 100);
    for (k = 0; k < 40u; k++) {
        A->retrig(k & 1u);
        if (k % 10u == 0u) A->sync();
        run(2205);
    }
    assert(!bad && A->voices() >= 1u);
    A->all_off();
    run(44100 * 3);
    printf("glcore: %u presets ok\n", n);
    return 0;
}
